"""
Download GOES-16 XRS 1-minute NetCDF4 data from NOAA NCEI for model pre-training.

Data source:
  https://data.ngdc.noaa.gov/platforms/solar-space-observing-satellites/goes/goes16/l2/data/xrsf-l2-avg1m_science/YYYY/MM/
  Files: sci_xrsf-l2-avg1m_g16_dYYYYMMDD_v{VERSION}.nc

Flare labels are generated by running our own detector on the GOES data —
no external catalog needed.

Usage:
    python scripts/download_goes.py --start 2020-01-01 --end 2023-12-31
    python scripts/download_goes.py --start 2020-01-01 --end 2020-06-30  # shorter test
"""

from __future__ import annotations

import argparse
import re
import sys
import time
from datetime import date, timedelta
from pathlib import Path

import requests
from tqdm import tqdm

# Project root on path so pipeline imports work when run as a script
ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(ROOT))

OUT_DIR = ROOT / "data" / "raw" / "goes"
OUT_DIR.mkdir(parents=True, exist_ok=True)

# Science-grade archive (~12-16 month lag, prefix: sci_)
NCEI_SCI = (
    "https://data.ngdc.noaa.gov/platforms/solar-space-observing-satellites"
    "/goes/goes16/l2/data/xrsf-l2-avg1m_science"
)
# Near-real-time archive (current + recent months, prefix: dn_)
NCEI_NRT = (
    "https://data.ngdc.noaa.gov/platforms/solar-space-observing-satellites"
    "/goes/goes16/l2/data/xrsf-l2-avg1m"
)


# ---------------------------------------------------------------------------
# Directory listing: find actual file name for a given date
# ---------------------------------------------------------------------------

def _list_month_files(year: int, month: int) -> dict[str, str]:
    """
    Return {YYYYMMDD: filename} for all days with a file in that month.
    Tries science-grade archive first; falls back to NRT if empty.
    """
    for base, pattern in [
        (NCEI_SCI, r'(sci_xrsf-l2-avg1m_g16_d(\d{8})_v[\d.-]+\.nc)'),
        (NCEI_NRT, r'(dn_xrsf-l2-avg1m_g16_d(\d{8})_v[\d.-]+\.nc)'),
    ]:
        url = f"{base}/{year}/{month:02d}/"
        try:
            r = requests.get(url, timeout=20)
            r.raise_for_status()
        except Exception:
            continue
        matches = re.findall(pattern, r.text)
        if not matches:
            continue
        def _ver(name: str) -> tuple:
            m2 = re.search(r"_v([\d.]+)\.nc$", name)
            return tuple(int(x) for x in m2.group(1).split(".")) if m2 else (0,)

        result: dict[str, str] = {}
        for fname, datestr in matches:
            # Keep whichever version is highest — HTML listing order is not guaranteed
            if datestr not in result or _ver(fname) > _ver(result[datestr]):
                result[datestr] = fname
        return result, base

    return {}, NCEI_SCI


def _download_file(year: int, month: int, fname: str, out_path: Path, base: str = NCEI_SCI) -> bool:
    url = f"{base}/{year}/{month:02d}/{fname}"
    try:
        r = requests.get(url, timeout=60, stream=True)
        r.raise_for_status()
        with open(out_path, "wb") as f:
            for chunk in r.iter_content(65536):
                f.write(chunk)
        return True
    except Exception as e:
        print(f"  Failed {fname}: {e}")
        if out_path.exists():
            out_path.unlink()
        return False


# ---------------------------------------------------------------------------
# Main downloader
# ---------------------------------------------------------------------------

def download_goes(start: date, end: date) -> list[Path]:
    """Download all available GOES-16 XRS 1-min files in [start, end]. Returns local paths."""
    downloaded: list[Path] = []

    # Iterate month by month
    current = date(start.year, start.month, 1)

    while current <= end:
        year, month = current.year, current.month
        month_files, base_url = _list_month_files(year, month)

        if not month_files:
            print(f"  No files found for {year}-{month:02d} (directory listing failed)")
        else:
            days_in_range = {
                d: fname for d, fname in month_files.items()
                if start <= date(int(d[:4]), int(d[4:6]), int(d[6:8])) <= end
            }

            for datestr, fname in tqdm(sorted(days_in_range.items()), desc=f"{year}-{month:02d}", leave=False):
                out = OUT_DIR / fname
                if out.exists():
                    downloaded.append(out)
                    continue
                if _download_file(year, month, fname, out, base_url):
                    downloaded.append(out)
                    time.sleep(0.2)

        # Advance to next month
        if month == 12:
            current = date(year + 1, 1, 1)
        else:
            current = date(year, month + 1, 1)

    return downloaded


# ---------------------------------------------------------------------------
# Verify a downloaded file is readable
# ---------------------------------------------------------------------------

def verify_nc(path: Path) -> bool:
    try:
        from pipeline.readers import read_goes_nc
        df = read_goes_nc(path)
        assert len(df) > 0 and "flux_long" in df.columns
        return True
    except Exception as e:
        print(f"  Verify failed {path.name}: {e}")
        return False


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Download GOES-16 XRS NetCDF4 files from NOAA NCEI")
    parser.add_argument("--start", default="2020-01-01")
    parser.add_argument("--end",   default="2023-12-31")
    parser.add_argument("--verify", action="store_true", help="Verify each file after download")
    args = parser.parse_args()

    start = date.fromisoformat(args.start)
    end   = date.fromisoformat(args.end)

    print(f"Downloading GOES-16 XRS 1-min data: {start} -> {end}")
    print(f"Output: {OUT_DIR}")

    files = download_goes(start, end)
    print(f"\nDownloaded {len(files)} files.")

    if args.verify and files:
        print("Verifying first 3 files...")
        for f in files[:3]:
            ok = verify_nc(f)
            print(f"  {f.name}: {'OK' if ok else 'FAIL'}")

    print("Done. Next step: python model/train.py --phase pretrain")
