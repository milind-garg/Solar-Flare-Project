"""
Evaluate a trained forecaster on held-out SoLEXS days.

Builds windows from the most recent `--holdout-frac` of processed SoLEXS files
(a time-based split, so we never test on days we could have trained on), labels
them from the master catalog, then prints the threshold sweep (TPR/FAR/TSS/HSS/
F1/AUC) and the lead-time analysis.

Usage:
    python scripts/evaluate_model.py                    # last 20% of days
    python scripts/evaluate_model.py --holdout-frac 0.3
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(ROOT))

import numpy as np
import pandas as pd
import torch
import yaml
import pipeline._compat  # noqa: F401

from pipeline.catalog import load_master_catalog
from pipeline.detector import detect_solexs_flares, events_to_dataframe
from model.cnn_lstm import load_checkpoint, load_norm
from model.features import build_feature_series, build_windows
from model.evaluate import predict_proba, threshold_sweep, compute_lead_times


def load_config(path: str = "config.yaml") -> dict:
    with open(ROOT / path) as f:
        return yaml.safe_load(f)


def build_test_set(cfg: dict, holdout_frac: float):
    """Return (X, y, times, catalog) from the most-recent holdout_frac of days.

    Labels are generated by running the detector on each test day's own SoLEXS
    data rather than looking them up in the all-days master catalog.  Using the
    shared catalog on test days would inflate apparent label cleanliness: the
    catalog is built after seeing all days (including test days), so events on
    test days may carry multi-instrument confirmation that wouldn't be available
    in a truly prospective evaluation.
    """
    proc_dir = ROOT / cfg["paths"]["processed_data"]
    fc = cfg["forecasting"]
    window_min, lead_min = fc["input_window_min"], fc["lead_time_min"]

    # Catalog is still loaded for the return value (display / downstream analysis),
    # but it is NOT used to generate per-window labels.
    catalog = load_master_catalog(ROOT / cfg["paths"]["master_catalog"])

    sxr_files = sorted(proc_dir.glob("*_solexs.parquet"))
    n_hold = max(1, int(len(sxr_files) * holdout_frac))
    test_files = sxr_files[-n_hold:]           # most-recent days = held out
    hxr_by_date = {f.name[:8]: f for f in proc_dir.glob("*_helios.parquet")}

    X_all, y_all, t_all = [], [], []
    for sf in test_files:
        try:
            sxr = pd.read_parquet(sf)
            date_key = sf.name[:8]
            hxr = pd.read_parquet(hxr_by_date[date_key]) if date_key in hxr_by_date else None
            feat = build_feature_series(sxr, hxr)

            # Per-day detector run — same logic that would run in production;
            # no look-ahead into future catalog entries.
            day_events = events_to_dataframe(detect_solexs_flares(sxr, cfg))
            local = pd.DatetimeIndex(day_events["peak_time"]) if not day_events.empty else None

            # return_times=True gets the exact anchor time for each surviving window
            # (NaN-skipped and negatively-subsampled windows shift the index, so a
            # contiguous feat.index slice would point to the wrong times).
            X, y, t = build_windows(feat, local, window_min=window_min,
                                     lead_time_min=lead_min, return_times=True)
            if len(X):
                X_all.append(X); y_all.append(y); t_all.append(t)
        except Exception as e:
            print(f"  Skip {sf.name}: {e}")

    if not X_all:
        raise RuntimeError("No test windows built from held-out days.")
    return (np.concatenate(X_all), np.concatenate(y_all),
            pd.DatetimeIndex(np.concatenate([t.values for t in t_all])), catalog)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--holdout-frac", type=float, default=0.2)
    ap.add_argument("--ckpt", default=None)
    args = ap.parse_args()

    cfg = load_config()
    ckpt = args.ckpt or str(ROOT / cfg["paths"]["model_checkpoint"])
    if not Path(ckpt).exists():
        raise FileNotFoundError(f"No checkpoint at {ckpt}. Train first.")

    device = "cuda" if torch.cuda.is_available() else "cpu"
    model = load_checkpoint(ckpt, device, cfg)
    mean, std = load_norm(ckpt, device)

    print(f"Evaluating {ckpt} on last {args.holdout_frac:.0%} of days (device={device})")
    X, y, times, catalog = build_test_set(cfg, args.holdout_frac)
    print(f"  Test windows: {len(X)}  |  positives: {y.mean():.2%}")

    y_prob = predict_proba(model, X, device=device, norm_mean=mean, norm_std=std)

    print("\n=== Threshold Sweep (TPR / FAR / TSS / HSS / F1 / AUC) ===")
    print(threshold_sweep(y, y_prob).to_string(index=False))

    thr = cfg["forecasting"]["alert_threshold"]
    alert_times = times[y_prob >= thr]
    flare_peaks = pd.DatetimeIndex(catalog["peak_time"]) if not catalog.empty else pd.DatetimeIndex([])
    print(f"\n=== Lead-Time Analysis (threshold={thr}) ===")
    for k, v in compute_lead_times(alert_times, flare_peaks, match_window_min=cfg["forecasting"]["lead_time_min"]).items():
        if k != "lead_times_min":
            print(f"  {k}: {v}")
